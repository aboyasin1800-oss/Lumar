SET NOCOUNT ON;

IF DB_NAME() <> N'LUMAR_ERP_ES_VALIDATION'
BEGIN
    THROW 50001, 'Rollback artifact must run only on LUMAR_ERP_ES_VALIDATION.', 1;
END

