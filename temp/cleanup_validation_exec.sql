SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
SET XACT_ABORT ON;
BEGIN TRANSACTION;

DECLARE @ProtectedLedger TABLE (LedgerAccountId int NOT NULL PRIMARY KEY);
INSERT INTO @ProtectedLedger(LedgerAccountId)
SELECT LedgerAccountId FROM dbo.LedgerAccounts
WHERE AccountCode IN (N'1000',N'1100',N'1101',N'1102',N'1103',N'1110',N'1120',N'1130',N'1150',N'1160',N'1200',N'2100',N'4100',N'4200',N'4210',N'5100',N'5200',N'5300',N'6100',N'FD0719001818A',N'FD0719001818B',N'FD0719001842C',N'FD0719001842D',N'SUPPLIER_ADVANCE',N'VAL0719013936');

DECLARE @ProtectedCash TABLE (CashAccountId int NOT NULL PRIMARY KEY);
INSERT INTO @ProtectedCash(CashAccountId) VALUES (1),(2);

DECLARE @TargetLedgerIds TABLE (LedgerAccountId int NOT NULL PRIMARY KEY);
INSERT INTO @TargetLedgerIds(LedgerAccountId)
SELECT LedgerAccountId
FROM dbo.LedgerAccounts
WHERE AccountCode NOT IN (N'1000',N'1100',N'1101',N'1102',N'1103',N'1110',N'1120',N'1130',N'1150',N'1160',N'1200',N'2100',N'4100',N'4200',N'4210',N'5100',N'5200',N'5300',N'6100',N'FD0719001818A',N'FD0719001818B',N'FD0719001842C',N'FD0719001842D',N'SUPPLIER_ADVANCE',N'VAL0719013936')
OR AccountCode = N'CA1000';

DECLARE @TargetCashIds TABLE (CashAccountId int NOT NULL PRIMARY KEY);
INSERT INTO @TargetCashIds(CashAccountId)
SELECT CashAccountId FROM dbo.CashAccounts WHERE CashAccountId NOT IN (1,2);

IF EXISTS (
  SELECT 1
  FROM @TargetLedgerIds t
  JOIN @ProtectedLedger p ON p.LedgerAccountId = t.LedgerAccountId
)
BEGIN
  RAISERROR('PROTECTED_LEDGER_INTERSECT_TARGET_DELETE_SET',16,1);
END;

IF EXISTS (
  SELECT 1
  FROM @TargetCashIds t
  JOIN @ProtectedCash p ON p.CashAccountId = t.CashAccountId
)
BEGIN
  RAISERROR('PROTECTED_CASH_INTERSECT_TARGET_DELETE_SET',16,1);
END;

DECLARE @CA1000LedgerId int = (SELECT LedgerAccountId FROM dbo.LedgerAccounts WHERE AccountCode = N'CA1000');
IF @CA1000LedgerId IS NOT NULL
BEGIN
  IF ((SELECT COUNT(*) FROM dbo.AccountRoleMappings WHERE LedgerAccountId = @CA1000LedgerId)
      + (SELECT COUNT(*) FROM dbo.CashAccounts WHERE LedgerControlAccountId = @CA1000LedgerId)
      + (SELECT COUNT(*) FROM dbo.JournalEntryLines WHERE LedgerAccountId = @CA1000LedgerId)
      + (SELECT COUNT(*) FROM dbo.SupplierFinancialPayments WHERE CashAccountId IN (SELECT CashAccountId FROM dbo.CashAccounts WHERE LedgerControlAccountId = @CA1000LedgerId))) > 0
  BEGIN
    RAISERROR('CA1000_HAS_LIVE_REFERENCES',16,1);
  END;
END;

DELETE FROM dbo.CashMovements
WHERE CashAccountId IN (SELECT CashAccountId FROM dbo.CashAccounts WHERE CashAccountId NOT IN (1,2));

DELETE FROM dbo.SupplierFinancialPayments
WHERE CashAccountId IN (SELECT CashAccountId FROM dbo.CashAccounts WHERE CashAccountId NOT IN (1,2));

DELETE FROM dbo.AccountRoleMappings
WHERE LedgerAccountId IN (
  SELECT LedgerAccountId
  FROM dbo.LedgerAccounts
  WHERE AccountCode NOT IN (N'1000',N'1100',N'1101',N'1102',N'1103',N'1110',N'1120',N'1130',N'1150',N'1160',N'1200',N'2100',N'4100',N'4200',N'4210',N'5100',N'5200',N'5300',N'6100',N'FD0719001818A',N'FD0719001818B',N'FD0719001842C',N'FD0719001842D',N'SUPPLIER_ADVANCE',N'VAL0719013936')
  OR AccountCode = N'CA1000'
);

DELETE FROM dbo.JournalEntryLines
WHERE LedgerAccountId IN (
  SELECT LedgerAccountId
  FROM dbo.LedgerAccounts
  WHERE AccountCode NOT IN (N'1000',N'1100',N'1101',N'1102',N'1103',N'1110',N'1120',N'1130',N'1150',N'1160',N'1200',N'2100',N'4100',N'4200',N'4210',N'5100',N'5200',N'5300',N'6100',N'FD0719001818A',N'FD0719001818B',N'FD0719001842C',N'FD0719001842D',N'SUPPLIER_ADVANCE',N'VAL0719013936')
  OR AccountCode = N'CA1000'
);

DELETE FROM dbo.CashAccounts
WHERE CashAccountId NOT IN (1,2);

DELETE FROM dbo.LedgerAccounts
WHERE AccountCode NOT IN (N'1000',N'1100',N'1101',N'1102',N'1103',N'1110',N'1120',N'1130',N'1150',N'1160',N'1200',N'2100',N'4100',N'4200',N'4210',N'5100',N'5200',N'5300',N'6100',N'FD0719001818A',N'FD0719001818B',N'FD0719001842C',N'FD0719001842D',N'SUPPLIER_ADVANCE',N'VAL0719013936')
  AND AccountCode <> N'CA1000';

DELETE FROM dbo.LedgerAccounts WHERE AccountCode = N'CA1000';

SELECT 'ProtectedLedgerAfter' AS GateName, COUNT(*) AS Value FROM dbo.LedgerAccounts WHERE AccountCode IN (N'1000',N'1100',N'1101',N'1102',N'1103',N'1110',N'1120',N'1130',N'1150',N'1160',N'1200',N'2100',N'4100',N'4200',N'4210',N'5100',N'5200',N'5300',N'6100',N'FD0719001818A',N'FD0719001818B',N'FD0719001842C',N'FD0719001842D',N'SUPPLIER_ADVANCE',N'VAL0719013936')
UNION ALL
SELECT 'ProtectedCashAfter', COUNT(*) FROM dbo.CashAccounts WHERE CashAccountId IN (1,2)
UNION ALL
SELECT 'TargetLedgerAfter', COUNT(*) FROM dbo.LedgerAccounts WHERE AccountCode NOT IN (N'1000',N'1100',N'1101',N'1102',N'1103',N'1110',N'1120',N'1130',N'1150',N'1160',N'1200',N'2100',N'4100',N'4200',N'4210',N'5100',N'5200',N'5300',N'6100',N'FD0719001818A',N'FD0719001818B',N'FD0719001842C',N'FD0719001842D',N'SUPPLIER_ADVANCE',N'VAL0719013936') AND AccountCode <> N'CA1000'
UNION ALL
SELECT 'TargetCashAfter', COUNT(*) FROM dbo.CashAccounts WHERE CashAccountId NOT IN (1,2)
UNION ALL
SELECT 'CashMovementsAfter', COUNT(*) FROM dbo.CashMovements
UNION ALL
SELECT 'JournalEntryLinesAfter', COUNT(*) FROM dbo.JournalEntryLines
UNION ALL
SELECT 'AccountRoleMappingsAfter', COUNT(*) FROM dbo.AccountRoleMappings
UNION ALL
SELECT 'CA1000After', COUNT(*) FROM dbo.LedgerAccounts WHERE AccountCode = N'CA1000';

COMMIT TRANSACTION;
